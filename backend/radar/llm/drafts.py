"""Step D2 of pm_pack/08: grounded explanation and correspondence draft for one finding.

    explain(finding, context, kind, issue) -> Draft with an Explanation
    letter(finding, context, kind, issue)  -> Draft with a Letter (models.Letter)

Order of sources: the cache (same model, prompt and payload), then Claude (radar.llm.client), then a deterministic
template built from the same evidence. Model text that fails grounding.validate() is never shown: the template is
used instead and the reason is reported. Nothing is ever sent; the letter is always marked as a draft.
"""
from __future__ import annotations

from dataclasses import dataclass, field

from pydantic import BaseModel, Field

from radar.config import settings
from radar.llm import client as C
from radar.llm import grounding as G
from radar.models import Letter

DRAFT_BANNER = "DRAFT for expert review. Generated by Filing Radar; not sent."


class Explanation(BaseModel):
    text: str = Field(description="Two to four plain-language sentences")
    cited_evidence_ids: list[str]


class LetterDraft(BaseModel):
    subject: str
    body_markdown: str
    cited_evidence_ids: list[str]


@dataclass
class Draft:
    output: BaseModel
    source: str                      # "claude-opus-5-5" (or the model that answered) | "cache: <model>" | "template"
    check: str                       # grounding summary
    notes: list[str] = field(default_factory=list)

    def as_dict(self) -> dict:
        return {"output": self.output.model_dump(), "source": self.source, "check": self.check, "notes": self.notes}


def _mhz(hz) -> str:
    """MHz exactly as the ITU rows file them (no rounding, so the grounding check finds the number)."""
    return "unknown" if hz is None else f"{hz / 1e6:g} MHz"


def _band(data: dict) -> str:
    if data.get("frequency_range_hz"):
        lo, hi = data["frequency_range_hz"]
        return f"{_mhz(lo)} to {_mhz(hi)}"
    if data.get("assigned_frequency_hz"):
        bw = data.get("bandwidth_hz")
        return f"{_mhz(data['assigned_frequency_hz'])}" + (f" with a bandwidth of {bw / 1e3:g} kHz" if bw else "")
    return "an unknown frequency"


def _sentence(text: str) -> str:
    """The deterministic reason as a sentence: capital first letter, one full stop at the end."""
    t = (text or "").strip().rstrip(".")
    return (t[:1].upper() + t[1:] + ".") if t else ""


def _ids(data: dict, kinds: tuple[str, ...], n: int) -> list[str]:
    return [e["id"] for e in data["evidence"] if e["kind"] in kinds][:n]


# ---- templates: deterministic, built only from the payload ------------------------------------------------------

def template_explanation(data: dict) -> Explanation:
    calc = data["calculation"]
    parts = [f"{data['title'] or data['notice_id']} ({data['special_section'] or 'section unknown'}) was rated "
             f"{data['concern']} by the screening rules. {_sentence(data['reason'])}"]
    if calc.get("result_value") is not None:
        lim = "no limit applies" if calc.get("limit_value") is None else f"the limit is {calc['limit_value']}"
        mar = "" if calc.get("margin_db") is None else f", margin {calc['margin_db']} dB"
        parts.append(f"The indicative calculation gives {calc['result_value']} {calc['result_unit']}; {lim}{mar}.")
    parts.append("A specialist should confirm the inputs against the cited rows before deciding.")
    cited = _ids(data, ("itu_row",), 1) + _ids(data, ("finnish_table_row",), 2) + _ids(data, ("regulation", "calculation"), 2)
    return Explanation(text=" ".join(parts), cited_evidence_ids=cited)


def template_letter(data: dict) -> LetterDraft:
    adm = data["administration"] or "the notifying administration"
    section = data["special_section"] or "the relevant section"
    finnish = [e["excerpt"] for e in data["evidence"] if e["kind"] == "finnish_table_row"][:3]
    calc = data["calculation"]
    ific = data["ific"]
    request = ("include Finland in the coordination of this network and provide the technical parameters needed "
               "to confirm compatibility" if section.startswith("CR/C") else
               "provide the technical characteristics of the network" if section.startswith("API") else
               "provide the technical parameters of the assignment and enter into coordination")
    lines = [
        f"To the Administration of {adm}",
        "",
        f"Finland refers to notice {data['notice_id']}, published in BR IFIC {ific['issue']} ({section}).",
        "",
        *([f"The filing uses {_band(data)}. In Finland this range is used as follows:", *[f"- {f}" for f in finnish]]
          if finnish else [f"The filing uses {_band(data)}. The Finnish use of this band is set out in Regulation M4."]),
        "",
        f"Finland's screening raised the following concern: {_sentence(data['reason'])}",
    ]
    if calc.get("result_value") is not None:
        lines += ["", f"The indicative calculation ({calc.get('method', 'method unknown')}) gives {calc['result_value']} {calc['result_unit']} "
                      + ("" if calc.get("limit_value") is None else f"against a limit of {calc['limit_value']}")
                      + ("" if calc.get("margin_db") is None else f" (margin {calc['margin_db']} dB)") + "."]
    lines += ["", f"Finland therefore requests the Administration of {adm} to {request}. "
                  "Finland reserves its rights with respect to the protection of its assignments.",
              "", "Yours faithfully,", "", "[Name, title], Traficom"]
    cited = _ids(data, ("itu_row",), 2) + _ids(data, ("finnish_table_row",), 3) + _ids(data, ("regulation", "calculation"), 2)
    return LetterDraft(subject=f"BR IFIC {ific['issue']}, {section}, notice {data['notice_id']}: request from Finland",
                       body_markdown="\n".join(lines), cited_evidence_ids=cited)


# ---- the two entry points ---------------------------------------------------------------------------------------

def _run(task: str, out_type: type[BaseModel], data: dict, *, effort: str, max_tokens: int, client=None) -> Draft:
    model = settings.llm_model
    texts = (lambda o: [o.text]) if task == "explain" else (lambda o: [o.subject, o.body_markdown])
    cached = G.cache_get(task, data, model)
    if cached:
        return Draft(out_type.model_validate(cached["output"]), f"cache: {cached['source']}", cached["check"], cached.get("notes", []))
    notes: list[str] = []
    try:
        res = C.generate(G.prompt(task), G.json.dumps(data, ensure_ascii=False), out_type,
                         effort=effort, max_tokens=max_tokens, client=client)
        check = G.validate(texts(res.output), res.output.cited_evidence_ids, data)
        if check.ok:
            notes.append(f"{res.input_tokens} input and {res.output_tokens} output tokens"
                         + ("; a refusal fallback model answered" if res.fallback_used else ""))
            draft = Draft(res.output, res.model, check.summary(), notes)
            G.cache_put(task, data, model, draft.as_dict())
            return draft
        notes.append(f"model text rejected by the grounding check ({check.summary()}); template shown instead")
    except C.LLMUnavailable as exc:
        notes.append(f"language model not used: {exc}")
    except C.LLMRefused as exc:
        notes.append(f"language model output not used: {exc}")
    tmpl = template_explanation(data) if task == "explain" else template_letter(data)
    return Draft(tmpl, "template", G.validate(texts(tmpl), tmpl.cited_evidence_ids, data).summary(), notes)


def explain(finding: dict, context: dict | None, kind: str, issue: int, client=None) -> Draft:
    return _run("explain", Explanation, G.payload(finding, context, kind, issue), effort="medium", max_tokens=4000, client=client)


def letter(finding: dict, context: dict | None, kind: str, issue: int, client=None) -> Draft:
    data = G.payload(finding, context, kind, issue)
    d = _run("letter", LetterDraft, data, effort="high", max_tokens=8000, client=client)
    o = d.output
    d.output = Letter(finding_id=finding["id"], to_administration=data["administration"] or "unknown",
                      subject=o.subject, body_markdown=f"*{DRAFT_BANNER}*\n\n{o.body_markdown}",
                      cited_evidence_ids=o.cited_evidence_ids)
    return d
